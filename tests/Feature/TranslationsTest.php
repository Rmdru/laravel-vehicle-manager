<?php

namespace Tests\Feature;

use App\Http\Middleware\SetLocale;
use App\Support\Navigation;
use Illuminate\Support\Facades\File;
use Tests\TestCase;

class TranslationsTest extends TestCase
{
    /**
     * The interface strings the Vue components translate with t().
     *
     * @return array<string, string> The file each string is used in, by string.
     */
    private function usedKeys(): array
    {
        $keys = [];

        foreach (File::allFiles(resource_path('js')) as $file) {
            $path = str_replace('\\', '/', $file->getRelativePathname());

            // Generated by Wayfinder.
            if (str_starts_with($path, 'actions/') || str_starts_with($path, 'routes/') || ! in_array($file->getExtension(), ['vue', 'ts'], true)) {
                continue;
            }

            preg_match_all('/\bt\(\s*([\'"])((?:\\\\.|(?!\1).)*?)\1/s', $file->getContents(), $matches);

            foreach ($matches[2] as $key) {
                $keys[str_replace("\\'", "'", $key)] = $path;
            }
        }

        return $keys;
    }

    public function test_every_interface_string_is_shared_with_the_frontend()
    {
        $shared = array_keys(Navigation::translations());

        foreach ($this->usedKeys() as $key => $path) {
            $this->assertContains($key, $shared, "[{$key}] in {$path} is not shared in Navigation::translations().");
        }
    }

    public function test_every_interface_string_is_translated()
    {
        foreach (array_keys(SetLocale::LOCALES) as $locale) {
            if ($locale === 'en') {
                continue;
            }

            $translations = json_decode(File::get(lang_path($locale.'.json')), true);

            foreach ($this->usedKeys() as $key => $path) {
                $this->assertArrayHasKey($key, $translations, "[{$key}] in {$path} has no {$locale} translation.");
            }
        }
    }
}
